/*
 * Содержание курса. Упражнения собираются конструкторами ниже, чтобы ключ
 * ответа нельзя было рассинхронизировать с плитками и вариантами, а верный
 * вариант не всегда стоял первым.
 *
 * Каждый модуль заканчивается диалогом: собеседник говорит реплику, ученик
 * выбирает уместный ответ. Реплики идут по порядку и складываются в сцену.
 */

// spin даёт стабильное число из текста: порядок вариантов разный у разных
// упражнений, но не меняется между запусками.
func spin(text string) int {
	h := fnv.New32a()
	_, _ = h.Write([]byte(text))
	return int(h.Sum32() & 0x7fffffff)
}

// placeAnswer вставляет верный вариант среди неверных не всегда в начало.
func placeAnswer(seed, answer string, wrong []string) []string {
	at := spin(seed) % (len(wrong) + 1)
	out := make([]string, 0, len(wrong)+1)
	out = append(out, wrong[:at]...)
	out = append(out, answer)
	out = append(out, wrong[at:]...)
	return out
}

// proper — слова, которые остаются с заглавной буквы и в середине фразы.
var proper = map[string]bool{"Kaspi": true, "IT": true, "Арман": true, "Айдана": true}

// tileText приводит слово к виду плитки: строчные буквы, как в Duolingo.
// Заглавная в начале фразы была бы подсказкой и портила середину ответа
// («мынаны» вместо «Мынаны»), поэтому первое слово ученик получит с заглавной
// уже на экране. Имена и сокращения вроде «QR-мен» остаются как есть.
func tileText(word string) string {
	if proper[word] {
		return word
	}
	runes := []rune(word)
	for _, r := range runes[1:] {
		if unicode.IsUpper(r) {
			return word
		}
	}
	return strings.ToLower(word)
}

// ch — выбор казахской фразы по русской.
func ch(prompt, answer string, wrong ...string) courseExercise {
	return courseExercise{
		kind: "choice", prompt: prompt, answer: answer,
		options: placeAnswer(prompt, answer, wrong),
	}
}

// build собирает фразу из слов. Лишние слова в банке сбивают с толку,
// а порядок плиток не совпадает с верным.
func build(ru, kk string, extra ...string) courseExercise {
	words := strings.Fields(kk)
	for i, word := range words {
		words[i] = tileText(word)
	}
	for i, word := range extra {
		extra[i] = tileText(word)
	}
	bank := append(append([]string{}, words...), extra...)
	// Стабильная перестановка по хэшу слова и места.
	for i := len(bank) - 1; i > 0; i-- {
		j := spin(ru+bank[i]) % (i + 1)
		bank[i], bank[j] = bank[j], bank[i]
	}
	// Если слова уже стоят в верном порядке (лишние не мешают), ответ очевиден.
	if inOrder(bank, words) {
		for i, j := 0, len(bank)-1; i < j; i, j = i+1, j-1 {
			bank[i], bank[j] = bank[j], bank[i]
		}
	}
	tiles := make([]seedItem, 0, len(bank))
	for i, text := range bank {
		tiles = append(tiles, seedItem{id: "t" + strconv.Itoa(i+1), text: text})
	}
	used := map[string]bool{}
	order := make([]string, 0, len(words))
	for _, word := range words {
		for _, tile := range tiles {
			if tile.text == word && !used[tile.id] {
				used[tile.id] = true
				order = append(order, tile.id)
				break
			}
		}
	}
	return courseExercise{
		kind: "assemble", prompt: "Соберите: «" + ru + "»",
		tiles: tiles, order: order,
	}
}

// inOrder сообщает, идут ли слова в банке в том же порядке, что в ответе.
func inOrder(bank, words []string) bool {
	next := 0
	for _, text := range bank {
		if next < len(words) && text == words[next] {
			next++
		}
	}
	return next == len(words)
}

// pair — казахская фраза и её перевод для сопоставления.
type pair struct{ kk, ru string }

// match соединяет фразы с переводами. Правая колонка сдвинута, чтобы пары
// не стояли друг против друга.
func match(pairs ...pair) courseExercise {
	left := make([]seedItem, 0, len(pairs))
	right := make([]seedItem, 0, len(pairs))
	key := make([][2]string, 0, len(pairs))
	for i, p := range pairs {
		left = append(left, seedItem{id: "l" + strconv.Itoa(i+1), text: p.kk})
		key = append(key, [2]string{"l" + strconv.Itoa(i+1), "r" + strconv.Itoa(i+1)})
	}
	for i := range pairs {
		src := (i + 1) % len(pairs)
		right = append(right, seedItem{id: "r" + strconv.Itoa(src+1), text: pairs[src].ru})
	}
	return courseExercise{
		kind: "match", prompt: "Соедините фразу с переводом",
		pairsLeft: left, pairsRight: right, pairs: key,
	}
}

// say — реплика собеседника. goal говорит ученику, что нужно сказать, а
// replies — принятые ответы, от самого простого к чуть более сложным: любой
// из них засчитывается. Плитки и ключ собирает buildScenes, когда известны
// все реплики урока.
func say(speaker, line, hint, goal string, replies ...string) courseExercise {
	return courseExercise{
		kind: "dialogue", prompt: line, speaker: speaker, hint: hint,
		goal: goal, answer: replies[0], replies: replies,
	}
}

// withHelp добавляет подсказку к сложной реплике: смысл слов, но не готовый ответ.
func (e courseExercise) withHelp(text string) courseExercise {
	e.help = text
	return e
}

// replyWords режет ответ на слова без знаков препинания: плитка «келемін.»
// выглядела бы странно, а знаки ученику ставить не нужно.
func replyWords(reply string) []string {
	words := strings.Fields(reply)
	for i, word := range words {
		words[i] = strings.Trim(word, ".,!?")
	}
	return words
}

// buildScenes собирает для каждой реплики общий банк слов из всех принятых
// ответов, ключ (по списку плиток на каждый ответ) и две лишние плитки из
// других реплик той же сцены: они по теме, но в этой реплике не нужны.
func buildScenes() {
	for s := range courseStarter {
		for l := range courseStarter[s].lessons {
			lesson := &courseStarter[s].lessons[l]
			var pool []string
			for _, e := range lesson.exercises {
				if e.kind != "dialogue" {
					continue
				}
				for _, reply := range e.replies {
					pool = append(pool, replyWords(reply)...)
				}
			}
			for i := range lesson.exercises {
				if lesson.exercises[i].kind == "dialogue" {
					fillScene(&lesson.exercises[i], pool)
				}
			}
		}
	}
}

// uniqueReplies убирает ответы, которые отличаются только регистром или знаками.
func uniqueReplies(replies []string) []string {
	seen := map[string]bool{}
	out := make([]string, 0, len(replies))
	for _, reply := range replies {
		key := strings.ToLower(strings.Join(replyWords(reply), " "))
		if seen[key] {
			continue
		}
		seen[key] = true
		out = append(out, reply)
	}
	return out
}

func fillScene(e *courseExercise, pool []string) {
	e.replies = uniqueReplies(e.replies)
	// Банк: каждое слово столько раз, сколько оно встречается в самом
	// длинном из ответов.
	var bank []string
	have := map[string]int{}
	for _, reply := range e.replies {
		seen := map[string]int{}
		for _, word := range replyWords(reply) {
			key := strings.ToLower(word)
			seen[key]++
			if seen[key] > have[key] {
				have[key]++
				bank = append(bank, tileText(word))
			}
		}
	}
	// Две лишние плитки, стабильно выбранные по реплике.
	var extra []string
	used := map[string]bool{}
	for _, word := range pool {
		key := strings.ToLower(word)
		if have[key] > 0 || used[key] {
			continue
		}
		used[key] = true
		extra = append(extra, word)
	}
	for picked := 0; picked < 2 && len(extra) > 0; picked++ {
		at := spin(e.prompt+strings.Repeat("+", picked)) % len(extra)
		bank = append(bank, tileText(extra[at]))
		extra = append(extra[:at], extra[at+1:]...)
	}
	for k := len(bank) - 1; k > 0; k-- {
		j := spin(e.prompt+bank[k]) % (k + 1)
		bank[k], bank[j] = bank[j], bank[k]
	}
	lower := make([]string, len(bank))
	for k, word := range bank {
		lower[k] = strings.ToLower(word)
	}
	// Первый ответ не должен лежать в банке уже готовым.
	first := replyWords(e.replies[0])
	firstLower := make([]string, len(first))
	for k, word := range first {
		firstLower[k] = strings.ToLower(word)
	}
	if inOrder(lower, firstLower) {
		for a, b := 0, len(bank)-1; a < b; a, b = a+1, b-1 {
			bank[a], bank[b] = bank[b], bank[a]
			lower[a], lower[b] = lower[b], lower[a]
		}
	}
	e.tiles = make([]seedItem, 0, len(bank))
	for k, word := range bank {
		e.tiles = append(e.tiles, seedItem{id: "t" + strconv.Itoa(k+1), text: word})
	}
	e.variants = make([][]string, 0, len(e.replies))
	for _, reply := range e.replies {
		taken := map[string]bool{}
		ids := make([]string, 0)
		for _, word := range replyWords(reply) {
			for k, tile := range e.tiles {
				if lower[k] == strings.ToLower(word) && !taken[tile.id] {
					taken[tile.id] = true
					ids = append(ids, tile.id)
					break
				}
			}
		}
		e.variants = append(e.variants, ids)
	}
}

